"""Provenance vocabulary.

Charter rule 2 and 3: never pretend synthetic data is real, never pretend external data was
collected by SHAZA. These enums exist so that rule lives in the schema rather than in a caption
somebody forgets to update. Every stored value carries one.
"""

from enum import StrEnum


class SourceKind(StrEnum):
    """Where a source sits relative to SHAZA."""

    EXTERNAL_API = "external_api"        # fetched live from a third party
    PUBLIC_DATASET = "public_dataset"    # downloaded bulk data (FAOSTAT, World Bank...)
    SYNTHETIC = "synthetic"              # generated by SHAZA's own simulator
    FIELD_OBSERVATION = "field_observation"  # measured by SHAZA on real land -- stage 9


class Provenance(StrEnum):
    """What kind of claim a single value is making.

    The distinction that matters most here is OBSERVED vs REANALYSIS. Open-Meteo's historical
    archive is ERA5, which is a reanalysis: a physical model run against assimilated
    observations. It is excellent data, and it is *not* a thermometer reading from Musanze.
    Calling it OBSERVED would be exactly the kind of quiet lie this enum exists to prevent.
    """

    OBSERVED = "observed"        # a real instrument measured this
    REANALYSIS = "reanalysis"    # model output constrained by assimilated observations
    FORECAST = "forecast"        # a prediction about a time that has not happened
    SIMULATED = "simulated"      # SHAZA's synthetic farm -- not a real place or season
    DERIVED = "derived"          # computed by SHAZA from other stored values

    @property
    def is_measurement(self) -> bool:
        """True only for values a real instrument produced."""
        return self is Provenance.OBSERVED

    @property
    def label(self) -> str:
        """Short human-facing tag. The UI renders this, never the raw value."""
        return {
            Provenance.OBSERVED: "Observed",
            Provenance.REANALYSIS: "Reanalysis (modeled)",
            Provenance.FORECAST: "Forecast",
            Provenance.SIMULATED: "Synthetic / simulated",
            Provenance.DERIVED: "Derived by SHAZA",
        }[self]


class Maturity(StrEnum):
    """How far a record has been checked. Mirrors the landing site's Provenance type."""

    ILLUSTRATIVE = "illustrative"
    IN_PROGRESS = "in-progress"
    VERIFIED = "verified"
